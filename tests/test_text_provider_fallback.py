from unittest.mock import Mock

import pytest

from src.integrations.text_provider_manager import (
    TextProviderManager,
    TextProviderManagerError,
)
from src.integrations.providers.text.text_provider_errors import (
    TextProviderAccessError,
    TextProviderQuotaError,
)


@pytest.fixture
def manager():
    """Create a manager with mock providers."""

    instance = TextProviderManager()

    instance.provider_order = ["openai", "claude", "gemini"]

    instance.PROVIDERS = {
        "openai": Mock(),
        "claude": Mock(),
        "gemini": Mock(),
    }

    return instance


def test_generation_falls_back_to_next_provider(manager):
    """OpenAI and Claude fail; Gemini succeeds."""

    manager.PROVIDERS["openai"].generate_text.side_effect = (
        TextProviderAccessError("Invalid API key")
    )

    manager.PROVIDERS["claude"].generate_text.side_effect = (
        TextProviderQuotaError("Quota exhausted")
    )

    manager.PROVIDERS["gemini"].generate_text.return_value = (
        "Generated by Gemini"
    )

    result = manager.generate_text(query="Explain AI agents")

    assert result == "Generated by Gemini"

    manager.PROVIDERS["openai"].generate_text.assert_called_once()
    manager.PROVIDERS["claude"].generate_text.assert_called_once()
    manager.PROVIDERS["gemini"].generate_text.assert_called_once()


def test_generation_raises_when_all_providers_fail(manager):
    """Manager raises an error when no provider succeeds."""

    manager.PROVIDERS["openai"].generate_text.side_effect = (
        TextProviderAccessError("Invalid API key")
    )

    manager.PROVIDERS["claude"].generate_text.side_effect = (
        TextProviderQuotaError("Quota exhausted")
    )

    manager.PROVIDERS["gemini"].generate_text.side_effect = (
        TextProviderAccessError("Access denied")
    )

    with pytest.raises(TextProviderManagerError):
        manager.generate_text(query="Explain AI agents")

    for provider in manager.PROVIDERS.values():
        provider.generate_text.assert_called_once()